    fun of(id: String): CountryTimeZone? = byId[id]

    fun ofPlace(countryCode: String?, at: Component.Coordinates?): CountryTimeZone? {
        val candidates = if (countryCode == null) all else all.filter { it.countryCode == countryCode.uppercase() }
        if (at == null) return candidates.singleOrNull()?.takeIf { countryCode != null }
        val scale = cos(at.latitude * PI / 180)
        return candidates.minByOrNull {
            val north = it.coordinates.latitude - at.latitude
            val east = (it.coordinates.longitude - at.longitude) * scale
            north * north + east * east
        }
    }
